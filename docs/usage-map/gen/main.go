// Command gen writes docs/usage-map/data.generated.js, the generated half of the usage map
// (docs/usage-map/index.html). It reads the repository and the esc binary's own help, so the
// map's commands, flags, exit codes, targets, portal routes, packages, model guidance and
// example packs follow the code. Run it from the repository root:
//
//	go run ./docs/usage-map/gen          # write the data
//	go run ./docs/usage-map/gen --open   # write it, open the page, print where it is
//
// It writes one file and changes nothing else. Stdlib plus gopkg.in/yaml.v3 only.
package main

