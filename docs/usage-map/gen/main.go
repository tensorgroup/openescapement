// Which part of the system each package belongs to. Unknown packages go to "Other".
var packageArea = map[string]string{
	"config": "pipeline", "source": "pipeline", "pack": "pipeline", "render": "pipeline", "targets": "pipeline",
	"engine": "pipeline", "lockfile": "pipeline", "esc": "pipeline",
	"publisher": "reporting", "updatecheck": "reporting",
	"portal/web": "portal", "portal/store": "portal", "portal/publish": "portal", "portal/seed": "portal", "portal/charts": "portal",
	"cli": "cli", "tty": "cli", "guidance": "guidance", "shapetest": "test",
}

var areaGroups = []struct{ key, title, blurb string }{
	{"pipeline", "Policy pipeline", "Fetch, verify, render and write policy; record it in the lockfile."},
	{"cli", "Command line", "Parses commands and talks to the terminal."},
	{"reporting", "Reporting", "Telemetry to the portal and the update-freshness check."},
	{"portal", "Admin portal", "esc serve: pages, store, publishing, demo data, charts."},
	{"guidance", "Model guidance", "The curated models registry and vendor notes."},
	{"test", "Test only", "Helpers that only tests use."},
	{"other", "Other", "Packages not yet placed in docs/usage-map/gen."},
}

func packages(root string) (treemap, []edge, int, error) {
	internal := filepath.Join(root, "internal")
	byArea := map[string][]item{}
	var edges []edge
	tests := 0
	seenEdge := map[string]bool{}
	err := filepath.WalkDir(internal, func(path string, d os.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return err
		}
		if d.Name() == "testdata" || d.Name() == "static" || d.Name() == "templates" {
			return filepath.SkipDir
		}
		rel, _ := filepath.Rel(internal, path)
		rel = filepath.ToSlash(rel)
		fset := token.NewFileSet()
		pkgs, err := parser.ParseDir(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		var doc string
		files, pkgTests := 0, 0
		imports := map[string]bool{}
		// Map iteration order is random; walk the files sorted so the output is stable.
		byName := map[string]*ast.File{}
		for _, p := range pkgs {
			for name, f := range p.Files {
				byName[name] = f
			}
		}
		names := make([]string, 0, len(byName))
		for name := range byName {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			f := byName[name]
			if strings.HasSuffix(name, "_test.go") {
				for _, decl := range f.Decls {
					if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && strings.HasPrefix(fn.Name.Name, "Test") {
						pkgTests++
					}
				}
				continue
			}
			files++
			if f.Doc != nil && doc == "" {
				doc = f.Doc.Text()
			}
			for _, imp := range f.Imports {
				p, _ := strconv.Unquote(imp.Path.Value)
				if strings.HasPrefix(p, modulePath+"/internal/") {
					imports[strings.TrimPrefix(p, modulePath+"/internal/")] = true
				}
			}
		}
		if files == 0 || rel == "." {
			tests += pkgTests
			return nil
		}
		tests += pkgTests
		area := packageArea[rel]
		if area == "" {
			area = "other"
		}
		id := "pkg:" + rel
		deps := make([]string, 0, len(imports))
		for dep := range imports {
			deps = append(deps, dep)
		}
		sort.Strings(deps)
		for _, dep := range deps {
			key := id + ">" + dep
			if !seenEdge[key] {
				seenEdge[key] = true
				edges = append(edges, edge{From: id, To: "pkg:" + dep, Label: "imports"})
			}
		}
		byArea[area] = append(byArea[area], item{
			ID: id, Name: rel, Title: "internal/" + rel, Tone: "package", KindLabel: "Go package",
			Detail: fmt.Sprintf("%d files · %d tests", files, pkgTests),
			Desc:   strings.Join(strings.Fields(doc), " "), Chips: prefixAll(deps, "internal/"), ChipsLbl: "Imports",
			File: "internal/" + rel,
		})
		return nil
	})
	if err != nil {
		return treemap{}, nil, 0, err
	}
	var groups []group
	for _, ag := range areaGroups {
		list := byArea[ag.key]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool { return list[i].Name < list[j].Name })
		groups = append(groups, group{ID: "grp:pkg:" + ag.key, Title: ag.title, Blurb: ag.blurb, Items: list})
	}
	// Edges only between packages that exist on the map.
	have := map[string]bool{}
	for _, g := range groups {
		for _, it := range g.Items {
			have[it.ID] = true
		}
	}
	kept := edges[:0]
	for _, e := range edges {
		if have[e.From] && have[e.To] {
			kept = append(kept, e)
		}
	}
	// Count tests under cmd/ too.
	_ = filepath.WalkDir(filepath.Join(root, "cmd"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, "_test.go") {
			return err
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return nil
		}
		for _, decl := range f.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv == nil && strings.HasPrefix(fn.Name.Name, "Test") {
				tests++
			}
		}
		return nil
	})
	return treemap{Groups: groups}, kept, tests, nil
}

func prefixAll(list []string, prefix string) []string {
	out := make([]string, len(list))
	for i, s := range list {
		out[i] = prefix + s
	}
	return out
}

// ── targets: the compiled-in builtIns table ─────────────────────────────────

func targetTable(root string) (treemap, error) {
	path := filepath.Join(root, "internal", "targets", "targets.go")
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return treemap{}, err
	}
	consts := map[string]string{}
	var table *ast.CompositeLit
	ast.Inspect(f, func(n ast.Node) bool {
		switch v := n.(type) {
		case *ast.ValueSpec:
			for i, name := range v.Names {
				if i < len(v.Values) {
					if lit, ok := v.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
						consts[name.Name], _ = strconv.Unquote(lit.Value)
					}
					if name.Name == "builtIns" {
						table, _ = v.Values[i].(*ast.CompositeLit)
					}
				}
			}
		}
		return true
	})
	if table == nil {
		return treemap{}, errors.New("builtIns table not found in internal/targets/targets.go")
	}
	value := func(e ast.Expr) string {
		switch v := e.(type) {
		case *ast.BasicLit:
			s, _ := strconv.Unquote(v.Value)
			return s
		case *ast.Ident:
			return consts[v.Name]
		}
		return ""
	}
	kindText := map[string]string{
		"managed-block": "A managed block inside a file the team also edits.",
		"whole-file":    "A whole file that esc owns.",
		"skills-dir":    "Skill directories under .claude/skills/.",
		"mcp-config":    "Server entries merged into .mcp.json.",
	}
	g := group{ID: "grp:target:builtin", Title: "Built-in targets", Blurb: "The files esc writes into a governed repo, from internal/targets."}
	for _, el := range table.Elts {
		lit, ok := el.(*ast.CompositeLit)
		if !ok {
			continue
		}
		fields := map[string]string{}
		for _, kv := range lit.Elts {
			if p, ok := kv.(*ast.KeyValueExpr); ok {
				if k, ok := p.Key.(*ast.Ident); ok {
					fields[k.Name] = value(p.Value)
				}
			}
		}
		name, file, kind := fields["Name"], fields["File"], fields["Kind"]
		label := file
		switch {
		case label == "" && kind == "skills-dir":
			label = ".claude/skills/"
		case label == "" && kind == "mcp-config":
			label = ".mcp.json"
		}
		g.Items = append(g.Items, item{
			ID: "target:" + name, Name: label, Title: label + " (" + name + ")", Tone: "target", KindLabel: "Instruction target",
			Detail: kind, Desc: kindText[kind], Chips: []string{"target: " + name, "kind: " + kind}, File: "internal/targets/targets.go",
		})
	}
	return treemap{Groups: []group{g}}, nil
}

// ── portal routes: mux.HandleFunc / mux.Handle in internal/portal/web ───────

var routeCall = regexp.MustCompile(`mux\.Handle(?:Func)?\("([A-Z]+ )?([^"]+)"`)

func portalRoutes(root string) (treemap, error) {
	b, err := os.ReadFile(filepath.Join(root, "internal", "portal", "web", "server.go"))
	if err != nil {
		return treemap{}, err
	}
	areaTitle := map[string]string{"": "Overview", "fleet": "Fleet", "packs": "Packs", "usage": "Usage", "models": "Models", "api": "Telemetry API", "static": "Static files"}
	order := []string{}
	byArea := map[string][]item{}
	for _, m := range routeCall.FindAllStringSubmatch(string(b), -1) {
		method := strings.TrimSpace(m[1])
		path := m[2]
		seg := strings.Split(strings.Trim(path, "/"), "/")[0]
		if seg == "{$}" {
			seg = ""
		}
		if _, ok := byArea[seg]; !ok {
			order = append(order, seg)
		}
		name := strings.TrimSpace(method + " " + strings.ReplaceAll(path, "{$}", ""))
		tone := "route-get"
		if method == "POST" {
			tone = "route-post"
		}
		byArea[seg] = append(byArea[seg], item{
			ID: "route:" + name, Name: name, Tone: tone, KindLabel: "Portal route",
			Desc: "Served by esc serve.", File: "internal/portal/web/server.go",
		})
	}
	var groups []group
	for _, seg := range order {
		title := areaTitle[seg]
		if title == "" {
			title = "/" + seg
		}
		groups = append(groups, group{ID: "grp:route:" + seg, Title: title, Items: byArea[seg]})
	}
	if len(groups) == 0 {
		return treemap{}, errors.New("no routes found in internal/portal/web/server.go")
	}
	return treemap{Groups: groups}, nil
}

// ── model guidance: internal/guidance/models/models.yaml ────────────────────

type registry struct {
	Vendors []struct {
		Key    string `yaml:"key"`
		Name   string `yaml:"name"`
		Models []struct {
			ID       string   `yaml:"id"`
			Name     string   `yaml:"name"`
			Tier     string   `yaml:"tier"`
			Roles    []string `yaml:"roles"`
			Status   string   `yaml:"status"`
			Docs     []string `yaml:"docs"`
			Verified string   `yaml:"verified"`
			Starter  string   `yaml:"starter"`
		} `yaml:"models"`
	} `yaml:"vendors"`
}

func modelGuidance(root string) (treemap, int, error) {
	dir := filepath.Join(root, "internal", "guidance", "models")
	b, err := os.ReadFile(filepath.Join(dir, "models.yaml"))
	if err != nil {
		return treemap{}, 0, err
	}
	var reg registry
	if err := yaml.Unmarshal(b, &reg); err != nil {
		return treemap{}, 0, err
	}
	var groups []group
	for _, v := range reg.Vendors {
		g := group{ID: "grp:model:" + v.Key, Title: v.Name, Blurb: "Vendor notes: internal/guidance/models/" + v.Key + ".md"}
		for _, m := range v.Models {
			facts := []string{"Verified " + m.Verified}
			for _, d := range m.Docs {
				if u, err := url.Parse(d); err == nil && u.Host != "" {
					facts = append(facts, "Source: "+d)
				}
			}
			it := item{
				ID: "model:" + m.ID, Name: m.Name, Title: m.Name + " (" + m.ID + ")", Tone: "model-" + m.Status, KindLabel: "Model · " + m.Status,
				Detail: m.Tier, Desc: fmt.Sprintf("%s, %s tier, %s. Roles: %s.", m.ID, m.Tier, m.Status, strings.Join(m.Roles, ", ")),
				Chips: m.Roles, ChipsLbl: "Roles", Facts: facts, File: "internal/guidance/models/models.yaml",
			}
			if m.Starter != "" {
				if _, err := os.Stat(filepath.Join(dir, m.Starter)); err == nil {
					it.File = "internal/guidance/models/" + m.Starter
				}
			}
			g.Items = append(g.Items, it)
		}
		groups = append(groups, g)
	}
	return treemap{Groups: groups}, len(reg.Vendors), nil
}

// ── example packs: examples/packs/*/pack.yaml ───────────────────────────────

type manifest struct {
	Name        string `yaml:"name"`
	Version     string `yaml:"version"`
	Description string `yaml:"description"`
	Rules       []string
	Skills      []any `yaml:"skills"`
	MCP         struct {
		Servers map[string]any `yaml:"servers"`
	} `yaml:"mcp"`
	Catalog []struct {
		Name     string `yaml:"name"`
		Category string `yaml:"category"`
		Status   string `yaml:"status"`
		Notes    string `yaml:"notes"`
	} `yaml:"catalog"`
	Reporting *struct {
		Amendments string `yaml:"amendments"`
	} `yaml:"reporting"`
}

func examplePacks(root string) (treemap, error) {
	paths, err := filepath.Glob(filepath.Join(root, "examples", "packs", "*", "pack.yaml"))
	if err != nil {
		return treemap{}, err
	}
	sort.Strings(paths)
	var groups []group
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil {
			return treemap{}, err
		}
		var m manifest
		if err := yaml.Unmarshal(b, &m); err != nil {
			return treemap{}, fmt.Errorf("%s: %w", p, err)
		}
		dirRel, _ := filepath.Rel(root, filepath.Dir(p))
		dirRel = filepath.ToSlash(dirRel)
		g := group{ID: "pack:" + m.Name, Title: m.Name + " " + m.Version, Blurb: m.Description}
		for _, r := range m.Rules {
			g.Items = append(g.Items, item{ID: "pack:" + m.Name + ":rule:" + r, Name: strings.TrimSuffix(filepath.Base(r), ".md"), Title: r, Tone: "rule", KindLabel: "Rule file", Desc: "A rule fragment rendered into the instruction files.", File: dirRel + "/" + r})
		}
		for _, s := range m.Skills {
			path, name := "", ""
			switch v := s.(type) {
			case string:
				path = v
			case map[string]any:
				path, _ = v["path"].(string)
				name, _ = v["name"].(string)
			}
			if name == "" {
				name = filepath.Base(path)
			}
			g.Items = append(g.Items, item{ID: "pack:" + m.Name + ":skill:" + path, Name: name, Title: "Skill " + name, Tone: "skill", KindLabel: "Skill", Desc: "A skill directory synced into .claude/skills/.", File: dirRel + "/" + path})
		}
		servers := make([]string, 0, len(m.MCP.Servers))
		for s := range m.MCP.Servers {
			servers = append(servers, s)
		}
		sort.Strings(servers)
		for _, s := range servers {
			g.Items = append(g.Items, item{ID: "pack:" + m.Name + ":mcp:" + s, Name: s, Title: "MCP server " + s, Tone: "mcp", KindLabel: "MCP server", Desc: "Merged into .mcp.json.", File: dirRel + "/pack.yaml"})
		}
		for i, c := range m.Catalog {
			g.Items = append(g.Items, item{
				ID: fmt.Sprintf("pack:%s:catalog:%d", m.Name, i), Name: shortName(c.Name), Title: c.Name, Tone: "status-" + c.Status,
				KindLabel: "Catalog entry · " + c.Status, Detail: c.Status, Desc: strings.Join(strings.Fields(c.Notes), " "),
				Chips: []string{"category: " + c.Category, "status: " + c.Status}, File: dirRel + "/pack.yaml",
			})
		}
		if len(g.Items) > 0 {
			groups = append(groups, g)
		}
	}
	return treemap{Groups: groups}, nil
}

// shortName drops a trailing "(model-id)" so a catalog name fits its cell.
func shortName(s string) string {
	if i := strings.LastIndex(s, " ("); i > 0 {
		return s[:i]
	}
	return s
}

// ── open the page ───────────────────────────────────────────────────────────

func openPage(page string) {
	u := url.URL{Scheme: "file", Path: filepath.ToSlash(page)}
	fmt.Printf("\nOpened the usage map:\n  %s\n  %s\n", page, u.String())
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "darwin":
		cmd = exec.Command("open", page)
	case "windows":
		cmd = exec.Command("cmd", "/c", "start", "", page)
	default:
		cmd = exec.Command("xdg-open", page)
	}
	if err := cmd.Run(); err != nil {
		fmt.Println("  (Could not open a browser here. Open the path above by hand.)")
	}
}
