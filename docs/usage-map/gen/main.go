const modulePath = "github.com/tensorgroup/openescapement"

type flagInfo struct {
	Name string `json:"name"`
	Desc string `json:"desc,omitempty"`
}

type item struct {
	ID        string     `json:"id"`
	Name      string     `json:"name"`
	Title     string     `json:"title,omitempty"`
	Tone      string     `json:"tone"`
	Detail    string     `json:"detail,omitempty"`
	KindLabel string     `json:"kindLabel"`
	Desc      string     `json:"desc,omitempty"`
	Usage     string     `json:"usage,omitempty"`
	Flags     []flagInfo `json:"flags,omitempty"`
	Chips     []string   `json:"chips,omitempty"`
	ChipsLbl  string     `json:"chipsLabel,omitempty"`
	File      string     `json:"file,omitempty"`
	Facts     []string   `json:"facts,omitempty"`
	Status    string     `json:"status,omitempty"`
}

type group struct {
	ID    string `json:"id"`
	Title string `json:"title"`
	Blurb string `json:"blurb,omitempty"`
	Items []item `json:"items"`
}

type treemap struct {
	Groups []group `json:"groups"`
}

type edge struct {
	From  string `json:"from"`
	To    string `json:"to"`
	Label string `json:"label,omitempty"`
}

type stat struct {
	N      int    `json:"n"`
	Label  string `json:"label"`
	Target string `json:"target"`
}

type output struct {
	GeneratedAt string             `json:"generatedAt"`
	Commit      string             `json:"commit"`
	Stats       []stat             `json:"stats"`
	Treemaps    map[string]treemap `json:"treemaps"`
	Edges       []edge             `json:"edges"`
}

func main() {
	open := flag.Bool("open", false, "open the page after writing the data, and print where it is")
	flag.Parse()
	root, err := repoRoot()
	if err != nil {
		fail(err)
	}
	out, err := build(root)
	if err != nil {
		fail(err)
	}
	dest := filepath.Join(root, "docs", "usage-map", "data.generated.js")
	body, err := json.MarshalIndent(out, "", " ")
	if err != nil {
		fail(err)
	}
	js := "// GENERATED by docs/usage-map/gen — do not edit by hand.\n" +
		"// Regenerate: go run ./docs/usage-map/gen --open\n" +
		"window.USAGE_MAP_DATA = " + string(body) + ";\n"
	if err := os.WriteFile(dest, []byte(js), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("usage map: %s\n", summary(out))
	if *open {
		openPage(filepath.Join(root, "docs", "usage-map", "index.html"))
	}
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "usage map: %v\n", err)
	os.Exit(1)
}

func summary(o output) string {
	parts := make([]string, 0, len(o.Stats))
	for _, s := range o.Stats {
		parts = append(parts, fmt.Sprintf("%d %s", s.N, s.Label))
	}
	return strings.Join(parts, ", ")
}

// repoRoot walks up from the working directory to the go.mod that declares this module.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil && strings.Contains(string(b), "module "+modulePath) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("run from inside the openescapement repository")
		}
		dir = parent
	}
}

func build(root string) (output, error) {
	// generatedAt is the HEAD commit's date, not the wall clock, so a rerun on unchanged code
	// writes a byte-identical file (the file is committed and must not churn).
	o := output{GeneratedAt: gitOut(root, "log", "-1", "--format=%cI"), Commit: gitOut(root, "rev-parse", "--short", "HEAD"), Treemaps: map[string]treemap{}}

	cmds, err := commands(root)
	if err != nil {
		return o, fmt.Errorf("commands: %w", err)
	}
	o.Treemaps["commands"] = cmds

	pkgs, imports, tests, err := packages(root)
	if err != nil {
		return o, fmt.Errorf("packages: %w", err)
	}
	o.Treemaps["packages"] = pkgs
	o.Edges = append(o.Edges, imports...)

	targets, err := targetTable(root)
	if err != nil {
		return o, fmt.Errorf("targets: %w", err)
	}
	o.Treemaps["targets"] = targets

	routes, err := portalRoutes(root)
	if err != nil {
		return o, fmt.Errorf("routes: %w", err)
	}
	o.Treemaps["routes"] = routes

	models, vendors, err := modelGuidance(root)
	if err != nil {
		return o, fmt.Errorf("models: %w", err)
	}
	o.Treemaps["models"] = models

	packs, err := examplePacks(root)
	if err != nil {
		return o, fmt.Errorf("packs: %w", err)
	}
	o.Treemaps["packs"] = packs

	count := func(t treemap) int {
		n := 0
		for _, g := range t.Groups {
			n += len(g.Items)
		}
		return n
	}
	cmdCount := 0
	for _, g := range cmds.Groups {
		if g.ID != "grp:cmd:exit" {
			cmdCount += len(g.Items)
		}
	}
	o.Stats = []stat{
		{cmdCount, "esc commands", "cli"},
		{count(targets), "instruction targets", "targets"},
		{count(models), "models in the guidance", "models"},
		{vendors, "model vendors", "models"},
		{len(packs.Groups), "example packs", "packs"},
		{count(routes), "portal routes", "portal"},
		{count(pkgs), "internal packages", "engine"},
		{tests, "Go test functions", "engine"},
	}
	return o, nil
}

func gitOut(root string, args ...string) string {
	b, err := exec.Command("git", append([]string{"-C", root}, args...)...).Output()
	if err != nil {
		return "unknown"
	}
	return strings.TrimSpace(string(b))
}

// ── commands: from the esc binary's own help ────────────────────────────────

var (
	sigLine  = regexp.MustCompile(`^  esc (\S+)(?: (\S+))?(.*)$`)
	contLine = regexp.MustCompile(`^\s{20,}(\S.*)$`)
	exitPart = regexp.MustCompile(`(\d) ([^·]+)`)
)

// Where each command runs. A command missing here still appears, under "Other".
var commandPlace = map[string]string{
	"init": "repo", "sync": "repo", "status": "repo", "diff": "repo", "update": "repo", "render": "repo",
	"serve": "server", "pack add-skill": "pack", "pack update-skill": "pack", "pack outdated": "pack",
	"version": "any",
}

var placeGroups = []struct{ key, title, blurb string }{
	{"repo", "In a governed repo", "What developers and CI run where the policy lands."},
	{"pack", "In a pack repo", "Author commands: vendor and maintain external skills."},
	{"server", "On a server", "The admin portal."},
	{"any", "Anywhere", ""},
	{"other", "Other", "Commands not yet placed in docs/usage-map/gen."},
}

type command struct {
	name, usage, desc string
}

func commands(root string) (treemap, error) {
	dir, err := os.MkdirTemp("", "esc-usage-map-")
	if err != nil {
		return treemap{}, err
	}
	defer os.RemoveAll(dir)
	bin := filepath.Join(dir, "esc")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := exec.Command("go", "build", "-o", bin, "./cmd/esc")
	build.Dir = root
	if b, err := build.CombinedOutput(); err != nil {
		return treemap{}, fmt.Errorf("go build ./cmd/esc: %v\n%s", err, b)
	}
	help, err := exec.Command(bin, "help").Output()
	if err != nil {
		return treemap{}, fmt.Errorf("esc help: %w", err)
	}

	var cmds []*command
	var pending []*command // signatures still waiting for a shared description
	var exitCodes [][2]string
	sc := bufio.NewScanner(strings.NewReader(string(help)))
	for sc.Scan() {
		line := sc.Text()
		if m := sigLine.FindStringSubmatch(line); m != nil {
			name := m[1]
			if name == "pack" && m[2] != "" {
				name += " " + m[2]
			}
			sig, desc := splitTwoSpaces(strings.TrimSpace(strings.TrimPrefix(line, "  ")))
			c := &command{name: name, usage: sig, desc: desc}
			cmds = append(cmds, c)
			// Consecutive signatures without a description share the lines that follow them.
			if desc == "" && len(pending) > 0 && pending[len(pending)-1].desc == "" {
				pending = append(pending, c)
			} else {
				pending = []*command{c}
			}
			continue
		}
		if m := contLine.FindStringSubmatch(line); m != nil && len(pending) > 0 {
			for _, c := range pending {
				c.desc = strings.TrimSpace(c.desc + " " + m[1])
			}
			continue
		}
		if strings.HasPrefix(line, "Exit codes:") {
			for _, m := range exitPart.FindAllStringSubmatch(strings.TrimPrefix(line, "Exit codes:"), -1) {
				exitCodes = append(exitCodes, [2]string{m[1], strings.TrimSpace(m[2])})
			}
		}
		pending = nil
	}

	byPlace := map[string][]item{}
	for _, c := range cmds {
		args := strings.Fields(c.name)
		flags := commandFlags(bin, args)
		place := commandPlace[c.name]
		if place == "" {
			place = "other"
		}
		id := "cmd:" + strings.ReplaceAll(c.name, " ", "-")
		byPlace[place] = append(byPlace[place], item{
			ID: id, Name: c.name, Title: "esc " + c.name, Tone: "command", KindLabel: "esc command",
			Desc: c.desc, Usage: c.usage, Flags: flags, File: "internal/cli/cli.go",
		})
	}
	var groups []group
	for _, pg := range placeGroups {
		if len(byPlace[pg.key]) == 0 {
			continue
		}
		groups = append(groups, group{ID: "grp:cmd:" + pg.key, Title: pg.title, Blurb: pg.blurb, Items: byPlace[pg.key]})
	}
	if len(exitCodes) > 0 {
		g := group{ID: "grp:cmd:exit", Title: "Exit codes", Blurb: "What a script or CI gate reads from esc."}
		for _, ec := range exitCodes {
			g.Items = append(g.Items, item{ID: "exit:" + ec[0], Name: ec[0] + " " + ec[1], Title: "Exit code " + ec[0], Tone: "exit", KindLabel: "Exit code", Desc: ec[1], File: "internal/cli/cli.go"})
		}
		groups = append(groups, g)
	}
	return treemap{Groups: groups}, nil
}

// splitTwoSpaces splits "esc sync [--force]   Fetch, verify…" at the first run of 2+ spaces.
func splitTwoSpaces(s string) (string, string) {
	i := strings.Index(s, "  ")
	if i < 0 {
		return s, ""
	}
	return strings.TrimSpace(s[:i]), strings.TrimSpace(s[i:])
}

var flagLine = regexp.MustCompile(`^  -(\S+)(?: (\S+))?$`)

// commandFlags runs `esc <args> -h` and reads the flag package's defaults listing.
func commandFlags(bin string, args []string) []flagInfo {
	if len(args) == 1 && (args[0] == "version" || args[0] == "help") {
		return nil
	}
	cmd := exec.Command(bin, append(append([]string{}, args...), "-h")...)
	cmd.Dir = os.TempDir()
	b, _ := cmd.CombinedOutput() // -h exits non-zero by design
	var flags []flagInfo
	for _, line := range strings.Split(string(b), "\n") {
		if m := flagLine.FindStringSubmatch(line); m != nil {
			name := "--" + m[1]
			if m[2] != "" {
				name += " " + strings.ToUpper(m[2])
			}
			flags = append(flags, flagInfo{Name: name})
			continue
		}
		if strings.HasPrefix(line, "    \t") && len(flags) > 0 {
			f := &flags[len(flags)-1]
			f.Desc = strings.TrimSpace(f.Desc + " " + strings.TrimSpace(line))
		}
	}
	return flags
}

